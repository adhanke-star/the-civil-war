// Deterministic byte admission for the existing service worker; no asset copies.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath, pathToFileURL} from 'node:url';

const ROOT=fs.realpathSync(fileURLToPath(new URL('..',import.meta.url)));
const OUTPUT=path.join(ROOT,'offline-manifest.js');
const BANNER='// Generated by node tools/build-offline-manifest.mjs --write; do not edit.\n';
const digest=b=>createHash('sha256').update(b).digest('hex');
const sorted=a=>[...new Set(a)].sort();
const fail=message=>{throw Error('offline manifest: '+message);};

export function createOfflineManifest({root=ROOT}={}){
  const tracked=execFileSync('git',['ls-files','-z','src','vendor','assets','index.html','manifest.webmanifest'],{cwd:root,encoding:'utf8'})
    .split('\0').filter(Boolean).sort();
  const files={};
  for(const p of tracked){
    if(!/^(?:src|vendor|assets)\//.test(p)&&!['index.html','manifest.webmanifest'].includes(p))fail('unexpected runtime path');
    const resolved=new URL(p,'https://offline.invalid/scope/');
    if(p.split('/').some(part=>part==='..'||part.startsWith('.'))||/[\\%?#]/.test(p)
      ||resolved.origin!=='https://offline.invalid'||resolved.pathname!=='/scope/'+p||resolved.search||resolved.hash)fail('unsafe runtime path');
    const full=path.join(root,p),stat=fs.lstatSync(full);
    if(!stat.isFile()||stat.isSymbolicLink()||stat.size>=100000000||!fs.realpathSync(full).startsWith(root+path.sep))fail('unsafe file '+p);
    const bytes=fs.readFileSync(full);files[p]={bytes:bytes.length,sha256:digest(bytes)};
  }
  const json=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
  const groups={};
  const add=(id,members,triggers=members)=>{
    members=sorted(members);triggers=sorted(triggers);
    if(!members.length||!triggers.length||members.some(p=>!files[p])||triggers.some(p=>!members.includes(p)))fail('incomplete group '+id);
    groups[id]={members,triggers};
  };
  const base=tracked.filter(p=>/^(?:src|vendor)\/.*\.(?:js|css)$/.test(p)
    ||['index.html','manifest.webmanifest','assets/campaign.json','assets/decisions.json','assets/traits.json','assets/art/manifest.json'].includes(p)
    ||/^assets\/icons\//.test(p)||/^assets\/figures\/[^/]+\/soldier(?:-hybrid|-source)?\.json$/.test(p));
  for(const p of tracked.filter(p=>/^assets\/packs\/[^/]+\.json$/.test(p)))add('pack:'+path.basename(p,'.json'),[p]);
  for(const p of tracked.filter(p=>/^assets\/terrain\/[^/]+\.json$/.test(p))){
    const binary=path.posix.join(path.posix.dirname(p),json(p).heights.file);
    add('terrain:'+path.basename(p,'.json'),[p,binary]);
  }
  // The tier's variant records name physical pages too. Metadata alone never selects a tier.
  const references=(value,dir,out=[])=>{
    if(value&&typeof value==='object'){
      if(Object.hasOwn(value,'pages')){
        if(!Array.isArray(value.pages)||!value.pages.length)fail('empty figure page declaration');
        for(const page of value.pages){
          if(typeof page?.file!=='string'||!/^[-a-zA-Z0-9_.]+$/.test(page.file))fail('unsafe figure page declaration');
          const p=path.posix.join(dir,page.file);
          if(!files[p])fail('missing figure page '+p);
          out.push(p);
        }
      }
      for(const child of Object.values(value))references(child,dir,out);
    }
    return sorted(out);
  };
  for(const [side,dir]of [['US','union-infantry'],['CS','confederate-infantry']]){
    const p='assets/figures/'+dir+'/soldier.json',meta=json(p);
    for(const tier of ['field','close']){const pages=references(meta.tiers[tier],path.posix.dirname(p));add('figures:'+side+':'+tier,[p,...pages],pages);}
  }
  const hybrid='assets/figures/confederate-infantry/soldier-hybrid.json';
  const compact=references(json(hybrid).tiers.close,path.posix.dirname(hybrid));
  add('figures:CS:compact-close',[hybrid,'assets/figures/confederate-infantry/soldier-source.json',...compact],compact);
  for(const p of tracked.filter(p=>p.startsWith('assets/scenarios/')))add('scenario:'+path.basename(p),[p]);
  // Existing art/audio/portraits remain demand-loaded: admission reuses only actual visited members.
  const payload={schema:1,workerSha256:digest(fs.readFileSync(path.join(root,'sw.js'))),files,base:sorted(base),groups};
  return{...payload,generation:digest(JSON.stringify(payload))};
}

export const serializeOfflineManifest=manifest=>BANNER+'self.CW_OFFLINE = '+JSON.stringify(manifest,null,1)+';\n';

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
  const args=process.argv.slice(2);
  if(args.length!==1||!['--check','--write'].includes(args[0]))fail('use exactly --check or --write');
  const expected=serializeOfflineManifest(createOfflineManifest());
  if(args[0]==='--check'){
    if(!fs.existsSync(OUTPUT)||fs.readFileSync(OUTPUT,'utf8')!==expected)fail('generated bytes drift; run --write');
    console.log('OFFLINE MANIFEST exact');
  }else{
    if(fs.realpathSync(path.dirname(OUTPUT))!==ROOT||!OUTPUT.startsWith(ROOT+path.sep))fail('output outside root');
    if(fs.existsSync(OUTPUT)&&(fs.lstatSync(OUTPUT).isSymbolicLink()||!fs.readFileSync(OUTPUT,'utf8').startsWith(BANNER)))fail('refuse foreign output');
    fs.writeFileSync(OUTPUT,expected);
    console.log('OFFLINE MANIFEST generated');
  }
}
